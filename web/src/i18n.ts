const sourceKeys: Record<string, string> = Object.fromEntries(
  Object.entries(ru).map(([key, value]) => [value, key]),
);
let locale: Locale = "ru";
let preference = "system";
try {
  const saved = localStorage.getItem("niceproxy-language");
  preference = saved ?? "system";
  if (preference === "system") locale = resolveLanguage(navigator.languages);
  else if (locales.some((item) => item.code === preference))
    locale = preference as Locale;
  else {
    preference = "system";
    locale = resolveLanguage(navigator.languages);
  }
} catch {
  /* SSR or storage disabled */
}

const listeners = new Set<() => void>();
let languageChangeInstalled = false;
export function resolveLanguage(languages: readonly string[]): Locale {
  for (const language of languages) {
    const base = language.toLowerCase().split(/[-_]/)[0];
    const found = locales.find(
      (item) => item.code === language || item.code === base,
    );
    if (found) return found.code;
  }
  return "en";
}
export function getLocale() {
  return locale;
}
export function getLanguagePreference() {
  return preference;
}
export function setLocale(next: string) {
  if (next === "system") locale = resolveLanguage(navigator.languages);
  else if (locales.some((item) => item.code === next)) locale = next as Locale;
  else return;
  preference = next;
  try {
    localStorage.setItem("niceproxy-language", next);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = locale;
  listeners.forEach((listener) => listener());
}
function installLanguageChangeListener() {
  if (languageChangeInstalled || typeof window === "undefined") return;
  languageChangeInstalled = true;
  window.addEventListener("languagechange", () => {
    if (preference === "system") setLocale("system");
  });
}
export function t(
  keyOrSource: string,
  values?: Record<string, string | number>,
) {
  const key = sourceKeys[keyOrSource] ?? keyOrSource;
  const value =
    (locale === "ru" ? ru[key] : undefined) ??
    translated[locale]?.[key] ??
    en[key] ??
    ru[key] ??
    keyOrSource;
  return values
    ? value.replace(/\{(\w+)\}/g, (_, name) =>
        String(values[name] ?? `{${name}}`),
      )
    : value;
}
export function useI18n() {
  const [, render] = useState(0);
  useEffect(() => {
    const listener = () => render((value) => value + 1);
    listeners.add(listener);
    installLanguageChangeListener();
    document.documentElement.lang = locale;
    return () => {
      listeners.delete(listener);
    };
  }, []);
  return { locale, preference, t, locales };
}
